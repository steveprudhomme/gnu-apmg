from pathlib import Path
import argparse
import hashlib
import html
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from photosemantique.taxonomy import validate_concepts, normalize

SOURCE = ROOT / 'third_party' / 'vocabularies'
PACKAGE = ROOT / 'photosemantique' / 'taxonomies'
DOCS = ROOT / 'docs' / 'ontology'
SCHEME = 'http://cv.iptc.org/newscodes/mediatopic/'


def load_sources():
    provenance = json.loads((SOURCE/'provenance.json').read_text(encoding='utf-8'))
    for source in provenance['sources']:
        if hashlib.sha256((SOURCE/source['file']).read_bytes()).hexdigest() != source['sha256']:
            raise ValueError('Source hash mismatch; review the update before rebuilding')
    original = json.loads((SOURCE/'iptc-mediatopics.json').read_text(encoding='utf-8'))
    concepts = []
    for row in original['conceptSet']:
        concepts.append({'uri': row['uri'], 'code': row['qcode'],
            'labels': {lang: text for lang, text in row['prefLabel'].items() if lang in ('fr','en-US','en-GB')},
            'definitions': {lang: text for lang, text in row.get('definition', {}).items() if lang in ('fr','en-US')},
            'broader': [p.replace('medtop:', SCHEME) for p in row.get('broader', [])],
            'retired': row.get('retired'), 'modified': row.get('modified'),
            'top_concept': row['uri'] in original.get('hasTopConcept', []),
            'aliases': [text for lang, text in row.get('altLabel', {}).items() for text in (text if isinstance(text,list) else [text]) if lang in ('fr','en-US','en-GB')]})
    validate_concepts(concepts)
    return provenance, original, sorted(concepts, key=lambda c:c['uri'])


def label(c):
    return c['labels'].get('fr') or c['labels'].get('en-US') or c['labels'].get('en-GB')


def render():
    provenance, original, concepts = load_sources()
    data = {'source': 'IPTC Media Topics', 'release': original['dateReleased'],
            'license': original['licenceLink'], 'attribution': original['copyrightHolder'],
            'transformation': 'FR/en-US/en-GB subset; original identifiers and broader preserved; no new mapping',
            'concepts': concepts}
    outputs = {PACKAGE/'iptc.json': json.dumps(data,ensure_ascii=False,indent=2)+'\n'}
    turtle = ['# IPTC Media Topics. Copyright IPTC. CC BY 4.0. FR/EN subset generated by GNU APMG.',
              '# Source and transformations: third_party/vocabularies/provenance.json',
              '@prefix skos: <http://www.w3.org/2004/02/skos/core#> .',
              '@prefix dct: <http://purl.org/dc/terms/> .',
              '@prefix owl: <http://www.w3.org/2002/07/owl#> .',
              f'<{SCHEME}> a skos:ConceptScheme ; dct:license <https://creativecommons.org/licenses/by/4.0/> .']
    for c in concepts:
        triples = ['a skos:Concept', f'skos:inScheme <{SCHEME}>']
        triples += ['skos:prefLabel '+json.dumps(t,ensure_ascii=False)+'@'+lang for lang,t in c['labels'].items()]
        triples += ['skos:definition '+json.dumps(t,ensure_ascii=False)+'@'+lang for lang,t in c['definitions'].items()]
        triples += [f'skos:broader <{p}>' for p in c['broader']]
        if c['top_concept']:
            triples.append(f'skos:topConceptOf <{SCHEME}>')
        if c['retired']:
            triples.append('owl:deprecated true')
        turtle.append('<'+c['uri']+'> '+' ;\n  '.join(triples)+' .')
    outputs[DOCS/'iptc-mediatopics.fr-en.ttl'] = '\n\n'.join(turtle)+'\n'
    profiles = json.loads((DOCS/'personal-photo-profile.json').read_text(encoding='utf-8'))
    index = {c['uri']:c for c in concepts}
    memberships = {}
    for group in profiles['groups']:
        seeds = set(group['concepts'])
        if any(uri not in index or index[uri]['retired'] for uri in seeds):
            raise ValueError('Profile seed missing/retired: '+group['id'])
        members = set(seeds)
        changed = True
        while changed:
            previous = len(members)
            members.update(c['uri'] for c in concepts if not c['retired'] and set(c['broader']) & members)
            changed = len(members) != previous
        memberships[group['id']] = sorted(members)
    catalogue = ['# Catalogue IPTC Media Topics — FR/EN', '',
        'Données : Copyright IPTC, CC BY 4.0. Version '+original['dateReleased']+'.',
        'Transformation GNU APMG : sélection des langues et présentation ; termes et parents non réécrits.',
        'Termes retirés conservés pour historique et exclus de la recherche ordinaire. Anglais affiché si français absent.', '']
    for state in (False,True):
        catalogue += ['## '+('Termes retirés — historique' if state else 'Termes actifs'), '']
        for c in concepts:
            if bool(c['retired']) != state: continue
            parents = ', '.join(label(index[p]) for p in c['broader']) or ('Sommet officiel' if c['top_concept'] else 'Parent non fourni')
            catalogue.append(f"- **{label(c)}** — {c['labels'].get('en-US','')} · [{c['code']}]({c['uri']}) · parents : {parents}")
    outputs[DOCS/'IPTC-CATALOGUE.md'] = '\n'.join(catalogue)+'\n'
    getty_selection = json.loads((DOCS/'getty-photo-selection.json').read_text(encoding='utf-8'))
    editorial = {r['uri']:r['editorial_label_fr'] for r in getty_selection['concepts']}
    getty = {}
    details = json.loads((SOURCE/'getty-aat-details.json').read_text(encoding='utf-8'))
    for binding in details['results']['bindings']:
        uri = binding['s']['value']
        c = getty.setdefault(uri, {'uri':uri, 'labels':{'en':binding['label']['value']},
            'editorial_label_fr':editorial[uri], 'broader':[], 'definitions':{},
            'retired':None, 'status':'Selected official record; retirement status not fetched'})
        if 'parent' in binding and binding['parent']['value'] not in c['broader']:
            c['broader'].append(binding['parent']['value'])
        if 'definition' in binding:
            c['definitions']['en'] = binding['definition']['value']
    if set(getty) != set(editorial):
        raise ValueError('Getty selection incomplete')
    getty_concepts = sorted(getty.values(),key=lambda c:c['uri'])
    validate_concepts(getty_concepts,closed=False)
    outputs[PACKAGE/'getty.json'] = json.dumps({'source':'Getty AAT restricted selection',
        'license':'https://opendatacommons.org/licenses/by/1-0/',
        'attribution':'Contains information from the J. Paul Getty Trust, Getty Research Institute, Art & Architecture Thesaurus, which is made available under the ODC Attribution License',
        'note':'French display labels are GNU APMG editorial translations; external broader references retained. Not a closed hierarchy or full AAT.',
        'concepts':getty_concepts},ensure_ascii=False,indent=2)+'\n'
    getty_lines = ['# Getty AAT — sélection pour les objets et la nature', '',
        'Contains information from the J. Paul Getty Trust, Getty Research Institute, Art & Architecture Thesaurus, which is made available under the ODC Attribution License.',
        'Licence : https://opendatacommons.org/licenses/by/1-0/. Français ci-dessous : traduction éditoriale GNU APMG, pas libellé officiel Getty. Sélection limitée, non exhaustive.', '',
        '| Présentation française GNU APMG | Libellé anglais Getty | Identifiant officiel |', '| --- | --- | --- |']
    for c in getty_concepts:
        getty_lines.append('| '+c['editorial_label_fr']+' | '+c['labels']['en']+' | ['+c['uri'].rsplit('/',1)[-1]+']('+c['uri']+') |')
    getty_lines += ['', '## Ambiguïtés exclues', '',
        'Les résultats de recherche bruts incluaient des oiseaux décoratifs, des dogs utilisés en menuiserie, des gliders de mobilier, des plants industriels et des bridges de musique. Ils ne sont pas des équivalents des animaux, plantes ou moyens de transport. Aucun exactMatch entre IPTC et Getty n’est ajouté.']
    outputs[DOCS/'GETTY-SELECTION.md'] = '\n'.join(getty_lines)+'\n'
    # Static offline catalogue: public vocabulary data only, no image or runtime CDN.
    options = '<option value="">Tous les thèmes officiels</option>'+''.join(
        '<option value="'+html.escape(g['id'])+'">'+html.escape(g['label_fr'])+'</option>' for g in profiles['groups'])
    rows = []
    for c in concepts:
        terms = label(c)+' '+c['labels'].get('en-US','')+' '+c['code']
        parents = ', '.join(label(index[p]) for p in c['broader']) or ('Sommet officiel' if c['top_concept'] else 'Parent non fourni')
        rows.append('<tr data-id="'+html.escape(c['uri'])+'" data-search="'+html.escape(normalize(terms),quote=True)+'" data-retired="'+str(bool(c['retired'])).lower()+'"><td>'+html.escape(label(c))+('</td><td>'+html.escape(c['labels'].get('en-US','')))+('</td><td>'+html.escape(parents))+'</td><td><a href="'+html.escape(c['uri'],quote=True)+'">'+html.escape(c['code'])+'</a>'+(' · RETIRÉ' if c['retired'] else '')+'</td></tr>')
    page = '''<!doctype html><html lang="fr"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>GNU APMG · Catalogue IPTC</title>
<style>body{font:17px system-ui;max-width:1450px;margin:35px auto;padding:0 20px;color:#172b42;background:#f4f7fb}input,select{font:inherit;padding:12px;margin:6px}table{border-collapse:collapse;width:100%;background:white}td,th{padding:12px;text-align:left;border-bottom:1px solid #d9e1e9}th{background:#19324c;color:white}a{color:#115c9d}tr[hidden]{display:none}</style>
<h1>GNU APMG · Catalogue des thèmes IPTC</h1><p>Consultation locale, sans photo ni requête réseau automatique. Copyright IPTC · <a href="https://creativecommons.org/licenses/by/4.0/">CC BY 4.0</a>. Présentation adaptée FR/EN par GNU APMG. Version '''+html.escape(original['dateReleased'])+'''.</p>
<p>Les vues « vie personnelle » sont une sélection éditoriale GNU APMG, pas une nouvelle hiérarchie IPTC. Un thème n'est pas une preuve visuelle ni une identification d'espèce.</p>
<input id="q" aria-label="Rechercher un thème" placeholder="Mariage, jardinage, anniversaire…"><select id="group" aria-label="Situation de vie">'''+options+'''</select><label><input type="checkbox" id="retired">Inclure les termes retirés</label><p id="count" aria-live="polite"></p>
<table><thead><tr><th>Français (ou anglais si absent)</th><th>Anglais</th><th>Parents officiels</th><th>Identifiant officiel</th></tr></thead><tbody>'''+''.join(rows)+'''</tbody></table>
<script>const groups='''+json.dumps(memberships,ensure_ascii=True).replace('<','\\u003c')+''';const rows=[...document.querySelectorAll('tbody tr')];function update(){const q=document.getElementById('q').value.normalize('NFKD').replace(/[\\u0300-\\u036f]/g,'').toLowerCase();const group=document.getElementById('group').value;const members=group?new Set(groups[group]):null;const retired=document.getElementById('retired').checked;let n=0;for(const row of rows){row.hidden=(!retired&&row.dataset.retired==='true')||!row.dataset.search.includes(q)||(members&&!members.has(row.dataset.id));if(!row.hidden)n++;}document.getElementById('count').textContent=n+' concepts affichés';}for(const id of ['q','group','retired'])document.getElementById(id).addEventListener('input',update);update();</script></html>'''
    outputs[DOCS/'catalogue.html'] = page
    return outputs


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in render().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                raise SystemExit('Generated taxonomy out of date: '+str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(text,encoding='utf-8')
    print('Taxonomy snapshot, hierarchy and generated catalogues verified')


if __name__ == '__main__':
    main()
